import { chromium } from 'playwright';
const ok = (c, m) => { console.log(c ? '✅' : '❌', m); if (!c) process.exitCode = 1; };
const b = await chromium.launch();
const p = await b.newPage({ serviceWorkers: 'block',  viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
const bad = []; p.on('response', (r) => r.status() >= 400 && bad.push(r.status() + ' ' + r.url()));
await p.goto('http://localhost:8090/');
ok((await p.textContent('h1')).includes('taka'), 'home page at the root');
await p.screenshot({ path: 'home.png', fullPage: true });
await p.click('.hero .btn.primary');
await p.waitForURL('**/AmrPotli/');
await p.waitForSelector('#login:not([hidden]), #app:not([hidden])');
ok(p.url().endsWith('/AmrPotli/'), 'Open AmrPotli goes to /AmrPotli/');
const icon = await p.evaluate(async () => (await fetch('icons/icon-192.png')).status);
const man = await p.evaluate(async () => (await (await fetch('manifest.json')).json()).start_url);
ok(icon === 200 && man === './', 'app files load from the new folder (icon, manifest start_url ./)');
await p.goto('http://localhost:8090/privacy.html');
await p.waitForURL('**/AmrPotli/privacy.html');
ok((await p.textContent('h1')) === 'Privacy', 'old privacy link forwards to /AmrPotli/privacy.html');
await p.click('text=← Back to the app');
await p.waitForURL('**/AmrPotli/');
ok(true, 'privacy page links back to the app');
// installed (standalone) app opened at the old root address
const ctx2 = await b.newContext({ serviceWorkers: 'block' });
const p2 = await ctx2.newPage();
await p2.addInitScript(() => { const mm = window.matchMedia; window.matchMedia = (q) => (q.includes('standalone') ? { matches: true, addEventListener() {} } : mm.call(window, q)); });
await p2.goto('http://localhost:8090/');
await p2.waitForURL('**/AmrPotli/');
ok(true, 'home-screen app opened at the old address goes to /AmrPotli/');
ok(bad.length === 0, 'no missing files: ' + bad.join(', '));
ok(errs.length === 0, 'no page errors ' + errs.join(' | '));
await b.close();
